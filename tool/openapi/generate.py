"""Optional strict OpenAPI JSON -> typed LIKE DTO/service generator.

Supported subset: named object schemas; required/nullable primitive/ref/array
fields; GET/POST/PUT/PATCH/DELETE; primitive path/query parameters; JSON schema
responses and JSON request bodies. Reject unsupported schema constructs instead
of emitting misleading partial bindings. No dependency on the package runtime.
"""
import argparse
import json
import re
from pathlib import Path

IDENT = re.compile(r'^[A-Za-z][A-Za-z0-9_]*$')
RESERVED = {'class', 'enum', 'final', 'var', 'void', 'switch', 'return', 'new', 'this', 'super', 'null', 'true', 'false', 'default', 'import', 'export', 'is', 'as', 'in', 'if', 'else', 'with', 'extends', 'implements', 'mixin', 'late', 'required', 'factory', 'static', 'const', 'get', 'set', 'operator', 'async', 'await', 'yield', 'throw', 'try', 'catch', 'finally', 'do', 'while', 'for', 'break', 'continue', 'assert', 'abstract', 'interface', 'sealed', 'base', 'typedef', 'dynamic'}

def identifier(value):
    if not IDENT.fullmatch(value) or value in RESERVED:
        raise ValueError('Unsupported Dart identifier: ' + value)
    return value

def literal(value):
    return "'" + json.dumps(value, ensure_ascii=False)[1:-1].replace("'", r"\'").replace('$', r'\$') + "'"

def canonical(source):
    # Preserve string contents while ignoring formatter whitespace/comments.
    pattern = r"'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"|//[^\n]*|/\*.*?\*/|[A-Za-z_][A-Za-z0-9_]*|[0-9]+|[^\s]"
    tokens = [token for token in re.findall(pattern, source, re.S)
              if not token.startswith('//') and not token.startswith('/*')]
    return [token for i, token in enumerate(tokens)
            if token != ',' or i + 1 == len(tokens) or tokens[i + 1] not in (')', '}')]


def generate(spec):
    if not str(spec.get('openapi', '')).startswith('3.0.'):
        raise ValueError('Only the documented OpenAPI 3.0 JSON subset is supported')
    schemas = spec.get('components', {}).get('schemas', {})
    def dtype(schema):
        if any(k in schema for k in ('oneOf', 'anyOf', 'allOf', 'enum', 'additionalProperties')):
            raise ValueError('Composition, enum and arbitrary map schemas require a hand-written parser')
        if '$ref' in schema:
            prefix = '#/components/schemas/'
            ref = schema['$ref']
            if not ref.startswith(prefix) or ref[len(prefix):] not in schemas:
                raise ValueError('Only local named schema references are supported')
            return identifier(ref[len(prefix):])
        typ = schema.get('type')
        if typ == 'array': return 'List<' + dtype(schema['items']) + '>'
        if typ not in {'string', 'integer', 'number', 'boolean'}:
            raise ValueError('Unsupported field type: ' + str(typ))
        return {'string': 'String', 'integer': 'int', 'number': 'double', 'boolean': 'bool'}[typ]
    def decode(schema, value):
        typ = dtype(schema)
        if '$ref' in schema: return typ + '.fromJson(Map<String, dynamic>.from(' + value + ' as Map))'
        if schema.get('type') == 'array':
            return '(' + value + ' as List).map((item) => ' + decode(schema['items'], 'item') + ').toList()'
        if typ == 'double': return '(' + value + ' as num).toDouble()'
        return value + ' as ' + typ
    def encode(schema, value):
        if '$ref' in schema: return value + '.toJson()'
        if schema.get('type') == 'array': return value + '.map((item) => ' + encode(schema['items'], 'item') + ').toList()'
        return value
    out = ["// GENERATED by tool/openapi/generate.py. Do not edit.", "import 'package:like/like.dart';", '']
    for name, schema in schemas.items():
        identifier(name)
        if schema.get('type') != 'object' or any(k in schema for k in ('oneOf','allOf','anyOf','additionalProperties')):
            raise ValueError('Named schemas must be plain objects')
        props = schema.get('properties', {})
        required = schema.get('required', [])
        if not set(required).issubset(props): raise ValueError('Unknown required property')
        fields = []
        for key, field in props.items():
            identifier(key)
            if key not in required and field.get('nullable', False):
                raise ValueError('Optional nullable fields require explicit presence wrappers')
            nullable = key not in required or field.get('nullable', False)
            fields.append((key, field, nullable))
        out += ['final class ' + name + ' {']
        for key, field, nullable in fields: out += ['  final ' + dtype(field) + ('?' if nullable else '') + ' ' + key + ';']
        out += ['  const ' + name + '({' + ', '.join(('required ' if key in required else '') + 'this.' + key for key, _, _ in fields) + '});']
        out += ['  factory ' + name + '.fromJson(Map<String, dynamic> json) => ' + name + '(']
        for key, field, nullable in fields:
            value = 'json[' + literal(key) + ']'
            out += ['    ' + key + ': ' + (value + ' == null ? null : ' if nullable else '') + decode(field, value) + ',']
        out += ['  );', '  Map<String, dynamic> toJson() => {']
        for key, field, nullable in fields:
            expression = encode(field, key)
            if nullable and (field.get('type') == 'array' or '$ref' in field):
                expression = expression.replace(key + '.', key + '?.', 1)
            out += ['    ' + literal(key) + ': ' + ('?' if key not in required else '') + expression + ',']
        out += ['  };', '}', '']
    out += ['final class GeneratedApi {', '  final LikeHttpClient client;', '  const GeneratedApi(this.client);']
    used = set()
    for path, operations in spec.get('paths', {}).items():
        for method, operation in operations.items():
            if method not in ('get','post','put','patch','delete'): raise ValueError('Unsupported path item: ' + method)
            name = identifier(operation['operationId'])
            if name in used: raise ValueError('Duplicate operationId')
            used.add(name)
            policy = operation.get('x-like-policy')
            if not isinstance(policy, dict) or not isinstance(policy.get('withAuth'), bool):
                raise ValueError('Every operation needs explicit x-like-policy withAuth and cacheTags/invalidates')
            policy_key = 'cacheTags' if method == 'get' else 'invalidates'
            tags = policy.get(policy_key)
            if not isinstance(tags, list) or any(not isinstance(x, str) for x in tags): raise ValueError('Explicit resource tag list required')
            responses = operation.get('responses', {})
            success = [v for k, v in responses.items() if str(k).startswith('2')]
            if len(success) != 1: raise ValueError('Exactly one success response schema required')
            response_schema = success[0]['content']['application/json']['schema']
            result_type = dtype(response_schema)
            params = ['CancelToken? cancelToken']
            query = []
            path_expr = literal(path)
            path_params = set()
            for param in operation.get('parameters', []):
                key = identifier(param['name']); location = param['in']; field = param['schema']
                typ = dtype(field)
                if typ.startswith('List<') or typ in schemas: raise ValueError('Only primitive parameters supported')
                required_param = param.get('required', False)
                if location == 'path':
                    if not required_param: raise ValueError('Path parameters must be required')
                    path_params.add(key)
                    path_expr = path_expr.replace('{' + key + '}', '${Uri.encodeComponent(' + key + '.toString())}')
                elif location == 'query': query.append('if (' + key + ' != null) ' + literal(key) + ': ' + key if not required_param else literal(key) + ': ' + key)
                else: raise ValueError('Only path/query parameters supported')
                params.append(('required ' if required_param else '') + typ + ('' if required_param else '?') + ' ' + key)
            if set(re.findall(r'\{([^}]+)\}', path)) != path_params: raise ValueError('Path parameters do not match template')
            body = operation.get('requestBody')
            if body:
                if method == 'get': raise ValueError('GET request body unsupported')
                if not body.get('required', False): raise ValueError('Only required JSON request bodies supported')
                body_schema = body['content']['application/json']['schema']
                params.append('required ' + dtype(body_schema) + ' body')
            out += ['  Future<ApiResult<' + result_type + '>> ' + name + '({' + ', '.join(params) + '}) async {']
            args = [path_expr, 'cancelToken: cancelToken', 'withAuth: ' + str(policy['withAuth']).lower(),
                    'requestConfig: const LikeRequestConfig(' + policy_key + ': [' + ', '.join(literal(tag) for tag in tags) + '])']
            if query: args += ['query: {' + ', '.join(query) + '}']
            if body: args += ['body: ' + encode(body_schema, 'body')]
            out += ['    final result = await client.' + method + '(' + ', '.join(args) + ');',
                    '    return result.mapSuccess((response) => ' + decode(response_schema, 'response.data') + ');', '  }']
    return '\n'.join(out + ['}', ''])

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('spec', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate(json.loads(args.spec.read_text()))
    if args.check:
        if canonical(args.output.read_text()) != canonical(output): raise SystemExit('Generated bindings are stale')
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(output)
